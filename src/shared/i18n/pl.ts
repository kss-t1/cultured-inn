/** Polish plural forms: 1 wydarzenie, 2–4 wydarzenia, 5+ wydarzeń (12–14 use the "many" form). */
export function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const d = n % 10;
  const dd = n % 100;
  return d >= 2 && d <= 4 && !(dd >= 12 && dd <= 14) ? few : many;
}

